import { test, expect } from "@playwright/test";
import { loginAdminUI } from "../../fixtures/ui-helpers";
import { apiUrl, authHeader, loginAsNewCustomer } from "../../fixtures/api-client";

test("admin books a customer's saved vehicle and records their payment", async ({ page, request }) => {
  const customer = await loginAsNewCustomer(request);
  const profile = await (await request.get(apiUrl("/auth/me"), { headers: authHeader(customer.token) })).json();
  const phone = profile.data.phone;
  const vehicle = await request.post(apiUrl("/users/me/vehicles"), { headers: authHeader(customer.token), data: { type: "hatchback", name: "Saved Staff Car", plate: "MP09AB1234" } });
  expect(vehicle.ok(), await vehicle.text()).toBeTruthy();
  const address = await request.post(apiUrl("/users/me/addresses"), { headers: authHeader(customer.token), data: { label: "Home", line: "Staff Test Residence, Indore", society: "Test Residence" } });
  expect(address.ok(), await address.text()).toBeTruthy();
  await loginAdminUI(page);
  await page.goto("/admin/bookings");
  await page.getByRole("link", { name: "Book a service", exact: true }).first().click();
  await expect(page).toHaveURL(/\/admin\/book-a-service$/);
  await expect(page.getByRole("heading", { name: "Book a service", exact: true })).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const dialog = page.getByRole("form", { name: "Book a service" });
  await dialog.getByPlaceholder("Search by name or phone number").fill(phone);
  await dialog.getByRole("button", { name: new RegExp(phone) }).click();
  await expect(dialog.getByRole("button", { name: /Saved Staff Car/ })).toBeVisible();
  await expect(dialog.getByLabel("Vehicle number", { exact: true })).toHaveValue("MP09AB1234");
  await expect(dialog.getByRole("button", { name: /Staff Test Residence, Indore/ })).toBeVisible();
  await dialog.getByRole("radio", { name: "Blue", exact: true }).click();
  await dialog.getByRole("button", { name: /Express Wash/ }).click();
  const schedule = dialog.locator("div.glass").filter({ has: page.getByRole("heading", { name: "Pick a date & time", exact: true }) });
  await schedule.getByRole("button").nth(2).click();
  await dialog.getByRole("button", { name: "11:00 AM", exact: true }).click();
  await expect(dialog.getByText("Total due", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Create booking", exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/bookings\/[a-f0-9]+$/);
  await expect(page.getByText(/Staff booking · Created by/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Record payment received" })).toBeDisabled();
  await page.getByLabel(/I have received the full/).check();
  await page.getByRole("button", { name: "Record payment received" }).click();
  await expect(page.getByText(/received by .* via CASH/)).toBeVisible();
});

test("admin uses the customer brand/model, colour and structured address inputs", async ({ page, request }) => {
  const customer = await loginAsNewCustomer(request);
  const profile = await (await request.get(apiUrl("/auth/me"), { headers: authHeader(customer.token) })).json();
  await loginAdminUI(page);
  await page.goto("/admin/book-a-service");
  await page.getByPlaceholder("Search by name or phone number").fill(profile.data.phone);
  await page.getByRole("button", { name: new RegExp(profile.data.phone) }).click();
  await page.getByRole("button", { name: "Can't find your car? Enter it manually", exact: true }).click();
  await page.getByLabel("Brand", { exact: true }).fill("Hyundai");
  await page.getByLabel("Model", { exact: true }).fill("Creta");
  await page.getByLabel("Vehicle category", { exact: true }).selectOption("suv");
  await page.getByLabel("Vehicle number", { exact: true }).fill("MP09AB5678");
  await page.getByRole("radio", { name: "White", exact: true }).click();
  await page.getByTestId("add-new-address-btn").click();
  const modal = page.getByRole("dialog", { name: "Add Service Address", exact: true });
  await modal.getByTestId("input-house-no").fill("Flat 402");
  await modal.getByTestId("input-society").fill("Green Valley");
  await modal.getByTestId("input-landmark").fill("Gate 2");
  await modal.getByTestId("input-pincode").fill("452001");
  const saved = page.waitForResponse(r => r.url().includes(`/admin/booking-customers/${customer.userId}/addresses`) && r.request().method() === "POST");
  await modal.getByTestId("save-address-btn").click();
  expect((await saved).ok()).toBeTruthy();
  await expect(modal).not.toBeVisible();
  await expect(page.getByRole("button", { name: /Flat 402, Green Valley, Gate 2/ })).toBeVisible();
  await page.getByRole("button", { name: /Express Wash/ }).click();
  const schedule = page.locator("div.glass").filter({ has: page.getByRole("heading", { name: "Pick a date & time", exact: true }) });
  await schedule.getByRole("button").nth(2).click();
  await page.getByRole("button", { name: "11:00 AM", exact: true }).click();
  await expect(page.getByRole("button", { name: "Create booking", exact: true })).toBeEnabled();
  const creation = page.waitForResponse(r => /\/admin\/bookings$/.test(r.url()) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Create booking", exact: true }).click();
  const response = await creation;
  expect(response.ok(), await response.text()).toBeTruthy();
  expect((await response.json()).data).toMatchObject({ vehicleName: "Hyundai Creta", vehicleType: "suv", vehiclePlate: "MP09AB5678", vehicleColor: "White", vehicleColorHex: "#f5f5f4", addressLine: expect.stringContaining("Flat 402, Green Valley, Gate 2") });
  const profileAfter = await (await request.get(apiUrl("/auth/me"), { headers: authHeader(customer.token) })).json();
  expect(profileAfter.data.addresses.some((a: { line: string }) => a.line.includes("Flat 402, Green Valley"))).toBeTruthy();
});
